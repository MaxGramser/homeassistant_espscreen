"""Build a plugin's own code as a module the firmware preview loads (docs/EMULATOR_ARCHITECTURE.md, "Plugins").

    python web/wasm/build_plugin.py <plugin folder> [--out <file.wasm>]

The preview is the shared firmware in WebAssembly, with the plugin host in it. A plugin is code of someone else, so it
is not in that binary: it is compiled here, with the same compiler, flags and headers, into a module of its own that
the browser loads into the preview's memory (Emscripten's dynamic linking). The plugin's tile is then drawn by the
plugin's own create(), on_state() and on_tick(), from what the app sends it, as on the glass.

What is built is the plugin's component (components/<name>/ beside its manifest, every .cpp in it) and a few lines
that do what the screen's build does for it (smart_display.register_plugin): make its object, hand it its id, its
version, its tiles' memory and its texts in every language, and run its setup(). The module's last section says what
it is and which preview it fits (`tessera`: id, version, api, abi).

Exit 0 and the file's path, or exit 2 with one sentence when this plugin cannot be shown in a browser: it needs or
brings hardware (a speaker, a camera), or its plugin.yaml makes ESPHome entities its component reads.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import sys
import tempfile

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import toolchain
from toolchain import ROOT, run

MANIFEST = 'tessera-plugin.yaml'


class Unfit(Exception):
    """This plugin has nothing a browser can run."""


def plugin_class(folder):
    """The plugin's class and the header that declares it: the one class of its component that is a tessera::Plugin."""
    found = []
    for header in sorted((folder / 'components').glob('*/*.h')):
        text = re.sub(r'//[^\n]*', '', header.read_text(encoding='utf-8', errors='replace'))
        scopes = re.findall(r'namespace\s+([\w:]+)\s*\{', text)
        for name, bases in re.findall(r'class\s+(\w+)\s*(?:final\s*)?:\s*([^{;]+)\{', text):
            if re.search(r'\btessera::Plugin\b', bases):
                found.append((header, '::'.join(scopes), name))
    if len(found) != 1:
        raise Unfit('its component has no class that is a tessera::Plugin' if not found else
                    'its components have more than one tessera::Plugin')
    return found[0]


def texts(folder):
    """Every text of the plugin for the screen (translations/<language>.json, part "screen"), by key and language."""
    table = {}
    for path in sorted((folder / 'translations').glob('*.json')):
        part = json.loads(path.read_text(encoding='utf-8')).get('screen') or {}
        for key, text in part.items():
            if isinstance(text, str):
                table.setdefault(key, {})[path.stem] = text
    return table


def literal(text):
    return json.dumps(str(text), ensure_ascii=False)


def glue(manifest, header, scope, name, table):
    """What the screen's build generates for a plugin (register_plugin), as one function the preview calls."""
    plugin = str(manifest['id'])
    lines = ['// Generated by web/wasm/build_plugin.py from the plugin\'s manifest and translations. Do not edit.',
             '#include <cstring>', '#include <string>', '#include <emscripten.h>', f'#include "{header.name}"', '',
             'namespace {', 'struct Text { const char *key, *language, *text; };', 'const Text TEXTS[] = {']
    for key in sorted(table):
        for language in sorted(table[key]):
            lines.append(f'  {{{literal(key)}, {literal(language)}, {literal(table[key][language])}}},')
    lines += ['  {nullptr, nullptr, nullptr},', '};',
              '// A key in the screen\'s language, else in its base language, else in English, as a build of that language carries.',
              'const char *said(const char *key, const std::string &language) {',
              '  const std::string base = language.substr(0, language.find(\'-\'));',
              '  const char *exact = nullptr, *near = nullptr, *english = nullptr;',
              '  for (const Text *t = TEXTS; t->key; ++t) {',
              '    if (std::strcmp(t->key, key) != 0) continue;',
              '    if (language == t->language) exact = t->text;',
              '    else if (base == t->language) near = t->text;',
              '    if (std::strcmp(t->language, "en") == 0) english = t->text;',
              '  }',
              '  return exact ? exact : near ? near : english;',
              '}', '}  // namespace', '',
              f'extern "C" EMSCRIPTEN_KEEPALIVE void tessera_boot_{plugin}(const char *language) {{',
              '  static bool booted = false;',
              '  if (booted) return;',
              '  booted = true;',
              f'  auto *plugin = new {scope}::{name}();' if scope else f'  auto *plugin = new {name}();',
              f'  plugin->set_identity({literal(plugin)}, {literal(manifest["version"])});']
    for tile in manifest.get('tiles') or []:
        if isinstance(tile.get('memory'), int):
            lines.append(f'  plugin->set_memory({literal(tile["id"])}, {tile["memory"]});')
    for saver in manifest.get('savers') or []:
        for flag, call in (('moves', 'set_moves'), ('taps', 'set_taps'), ('backdrop', 'set_backdrop')):
            if saver.get(flag) is True:
                lines.append(f'  plugin->{call}({literal(saver["id"])});')
    lines += ['  const std::string speaks = language ? language : "en";']
    for key in sorted(table):
        lines.append(f'  if (const char *text = said({literal(key)}, speaks)) plugin->set_text({literal(key)}, text);')
    lines += ['  plugin->setup();', '}', '']
    return '\n'.join(lines)


def section(name, payload):
    """A custom section of a WebAssembly module: what the module says about itself, read without running it."""
    def leb(n):
        out = bytearray()
        while True:
            byte, n = n & 0x7F, n >> 7
            out.append(byte | (0x80 if n else 0))
            if not n:
                return bytes(out)
    body = leb(len(name)) + name.encode() + payload
    return b'\0' + leb(len(body)) + body


def build(folder, out=None):
    folder = Path(folder).resolve()
    manifest = yaml.safe_load((folder / MANIFEST).read_text(encoding='utf-8')) or {}
    plugin = str(manifest.get('id') or '')
    if not re.fullmatch(r'[a-z][a-z0-9_]{0,63}', plugin):
        raise Unfit(f'{folder}: no plugin id in {MANIFEST}')
    # A browser has no speaker, microphone or camera of a screen (the plugins repository's bench says the same).
    hardware = sorted(set((manifest.get('requires') or {}).get('features') or []) | set(manifest.get('provides') or []))
    if hardware:
        raise Unfit(f'{plugin} needs or brings hardware ({", ".join(hardware)}): it shows on a screen only')
    if not (manifest.get('tiles') or manifest.get('savers') or manifest.get('cards') or manifest.get('bar_items')):
        raise Unfit(f'{plugin} draws nothing: no tile, card, top bar item or screensaver')
    # The component's own configuration is the manifest's and nothing else: a plugin.yaml that makes ESPHome entities
    # (a switch, a sensor of Home Assistant) for its component to read needs ESPHome's own code generation, which the
    # preview does not run for a plugin yet.
    package = folder / 'plugin.yaml'
    config = (yaml.safe_load(re.sub(r'!\w+', '', package.read_text(encoding='utf-8'))) or {}) if package.is_file() else {}
    own = {key: value for key, value in config.items() if key not in ('defaults', 'substitutions')}
    if any(value for value in own.values()) or len(own) > 1:
        raise Unfit(f'{plugin} has ESPHome entities of its own in plugin.yaml: not shown in the browser yet')
    header, scope, name = plugin_class(folder)
    sources = sorted(header.parent.glob('*.cpp'))
    toolchain.prepare()
    if not shutil.which('em++'):
        raise SystemExit('Emscripten is required; activate emsdk before building a plugin\'s module.')
    toolchain.check_compiler()
    flags = [*toolchain.flags(), f'-I{header.parent}', '-fPIC', '-std=c++17']
    out = Path(out).resolve() if out else folder / '.preview' / f'{plugin}.wasm'
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as work:
        work = Path(work)
        (work / 'boot.cpp').write_text(glue(manifest, header, scope, name, texts(folder)), encoding='utf-8')
        objects = []
        for index, path in enumerate([*sources, work / 'boot.cpp']):
            objects.append(work / f'{index}.o')
            run(['em++', *flags, '-c', path, '-o', objects[-1]])
        # A side module that keeps every symbol: what it shares with the preview through a header (an inline variable,
        # a static of an inline function) must be the preview's own, and only an exported symbol is.
        run(['em++', '-O2', '-sSIDE_MODULE=1', *objects, '-o', work / 'plugin.wasm'])
        about = {'id': plugin, 'version': str(manifest.get('version') or ''), 'api': str(manifest.get('api') or ''),
                 'abi': toolchain.plugin_abi()}
        out.write_bytes((work / 'plugin.wasm').read_bytes() + section('tessera', json.dumps(about, sort_keys=True).encode()))
    return out, about


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('folder')
    parser.add_argument('--out')
    args = parser.parse_args()
    try:
        path, about = build(args.folder, args.out)
    except Unfit as reason:
        print(f'Not built: {reason}.', file=sys.stderr)
        raise SystemExit(2)
    print(json.dumps({**about, 'file': str(path), 'bytes': path.stat().st_size}))
